"""Idempotent creates: every create takes an Idempotency-Key header, and a replay returns the original response.

CLAUDE.md, API conventions. Records live in the tenant-scoped `idempotency_keys` collection (sabha_core.models.
IdempotencyRecord), unique per (tenant, route, key) and deleted by MongoDB 24 h after creation (TTL index).

- No header: 400 `idempotency_key_required`. A key must be 1 to 255 visible ASCII characters, else 400
  `invalid_idempotency_key`.
- First request: a record is inserted as in_progress, the handler runs, and its status and body are stored.
- Same key again while the first is still running: 409 `request_in_progress`.
- Same key, same body, after it finished: the stored response, with `Idempotent-Replayed: true`.
- Same key, different body: 422 `idempotency_key_reused`.
- If the handler fails (any error), the record is removed, so the client can retry with the same key.

Keys are per tenant, so two tenants using the same key never see each other's responses. The key is a field of the
record, never its `_id` (ids are always generated by the server; sabha_core.repo).
"""

from __future__ import annotations

import hashlib
import json
import re
from collections.abc import Awaitable, Callable
from typing import Any

from fastapi.responses import JSONResponse
from pydantic import BaseModel
from pymongo.errors import DuplicateKeyError

from sabha_api.errors import ApiError, BadRequestError, ConflictError
from sabha_core.models import IdempotencyRecord
from sabha_core.repo import TenantRepo

HEADER = "Idempotency-Key"
REPLAYED_HEADER = "Idempotent-Replayed"
_KEY = re.compile(r"^[\x21-\x7e]{1,255}$")

Handler = Callable[[], Awaitable[tuple[int, dict[str, Any]]]]


class IdempotencyKeyRequiredError(BadRequestError):
    code, title = "idempotency_key_required", "Idempotency-Key required"


class InvalidIdempotencyKeyError(BadRequestError):
    code, title = "invalid_idempotency_key", "Invalid Idempotency-Key"


class IdempotencyKeyReusedError(ApiError):
    status, code, title = 422, "idempotency_key_reused", "Idempotency-Key reused"


class RequestInProgressError(ConflictError):
    code, title = "request_in_progress", "Request in progress"


def request_hash(body: BaseModel) -> str:
    canonical = json.dumps(body.model_dump(mode="json"), sort_keys=True, separators=(",", ":"), ensure_ascii=False)
    return hashlib.sha256(canonical.encode()).hexdigest()


async def idempotent(
    records: TenantRepo[IdempotencyRecord], *, key: str | None, route: str, body: BaseModel, handler: Handler
) -> JSONResponse:
    """Run `handler` once per (tenant, route, key) and return its response, or replay the stored one."""
    if key is None:
        raise IdempotencyKeyRequiredError(f"Send an {HEADER} header with every create request.")
    if not _KEY.match(key):
        raise InvalidIdempotencyKeyError(f"{HEADER} must be 1 to 255 visible ASCII characters.")
    digest = request_hash(body)
    record = IdempotencyRecord(route=route, key=key, request_hash=digest)
    try:
        record = await records.insert_one(record)
    except DuplicateKeyError:
        return await _replay(records, route=route, key=key, digest=digest)
    try:
        status, payload = await handler()
    except BaseException:
        await records.delete_one({"_id": record.id})
        raise
    await records.update_one(
        {"_id": record.id},
        {"$set": {"status": "done", "response_status": status, "response_body": payload}},
    )
    return JSONResponse(payload, status_code=status)


async def _replay(records: TenantRepo[IdempotencyRecord], *, route: str, key: str, digest: str) -> JSONResponse:
    existing = await records.find_one({"route": route, "key": key})
    if existing is None or existing.status != "done" or existing.response_status is None:
        raise RequestInProgressError("A request with this Idempotency-Key is still being processed. Retry shortly.")
    if existing.request_hash != digest:
        raise IdempotencyKeyReusedError("This Idempotency-Key was already used with a different request body.")
    return JSONResponse(
        existing.response_body or {}, status_code=existing.response_status, headers={REPLAYED_HEADER: "true"}
    )
